import { readFileSync, writeFileSync } from "node:fs";
import type { Cell, Landscape, OmittedCell, Product, TaskQueueProduct } from "./landscape-types.ts";

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

const isOmitted = (c: Cell | OmittedCell): c is OmittedCell => "omitted" in c;

const link = (url?: string, asOf?: string) =>
  url ? ` ([source](${url}), as of ${asOf ?? "?"})` : "";

function renderCell(c: Cell | OmittedCell): string {
  if (isOmitted(c)) return `_omitted_`;
  return `${esc(c.chip)} **${esc(c.name)}**: ${esc(c.summary)}${link(c.sourceUrl, c.asOf)}`;
}

function renderTable(label: string, products: Product[], columns: string[], cols: (p: Product) => string[]): string[] {
  if (products.length === 0) return [];
  const header = ["Product", ...columns, "Demoable", "Where it takes it"];
  const lines = [
    `### ${label}`,
    "",
    `| ${header.join(" | ")} |`,
    `| ${header.map(() => "---").join(" | ")} |`,
  ];
  for (const p of products) {
    const d = p.demoable;
    const demo =
      d.kind === "unknown" ? "unknown" : `**${d.kind}**: ${esc(d.summary ?? "")}${link(d.sourceUrl, d.asOf)}`;
    const dest = p.destination;
    const destOut =
      dest.summary === "unknown" ? "unknown" : `${esc(dest.summary)}${link(dest.sourceUrl, dest.asOf)}`;
    lines.push(`| ${[esc(p.name), ...cols(p), demo, destOut].join(" | ")} |`);
  }
  lines.push("");
  return lines;
}

export function renderLandscape(data: Landscape): string {
  const out: string[] = [
    "<!-- GENERATED by `bun scripts/render-landscape.ts` from landscape/matrix.json. Do not edit by hand. -->",
    "",
    "# Landscape: factories x components",
    "",
    "How other products handle the components covered in lesson 1: whether a person approves or edits the plan first,",
    "whether the plan becomes tasks that outlive the chat, whether those tasks carry criteria and dependencies,",
    "what judges a task done, whether the loop moves on to the next task by itself, and who drives that loop. Lesson 2 adds",
    "the design step: whether the planner reads the code first, what form its design takes, whether it names reuse or risks,",
    "who approves before work starts, and how the plan becomes tasks. Each cell is",
    "a paraphrase of a first-party page, with its source URL and the date it was fetched. Cells we could not source are",
    "omitted, not guessed. Task-queue options are not compared per component; they get one Queue column.",
    "",
    "**Names are not canonical.** The bold text in each cell is the product's own name for the",
    "capability, taken from its docs. The same stage goes by different names in different factories.",
    "",
    ...renderTable(
      "Factories and coding agents",
      data.products.filter((p) => p.kind === "factory"),
      data.components.map((c) => c.label),
      (p) => (p.kind === "factory" ? data.components.map((c) => renderCell(p.cells[c.id])) : []),
    ),
    ...renderTable(
      "Task-queue options",
      data.products.filter((p): p is TaskQueueProduct => p.kind === "task-queue"),
      ["Queue"],
      (p) => (p.kind === "task-queue" ? [renderCell(p.queue)] : []),
    ),
    "## Omitted cells",
    "",
  ];
  const omitted: string[] = [];
  for (const p of data.products)
    if (p.kind === "factory")
      for (const c of data.components) {
        const cell = p.cells[c.id];
        if (isOmitted(cell)) omitted.push(`- ${p.name} / ${c.label}: ${cell.omitted}`);
      }
  out.push(...(omitted.length ? omitted : ["None."]), "");
  out.push(
    "## Updating",
    "",
    "1. Edit `landscape/matrix.json`. Every populated cell needs `name` (the product's own term,",
    "   or the literal `unknown` if its docs give none), `summary` (a paraphrase of the page),",
    "   `sourceUrl` (https, on a host listed in the product's `allowedHosts`), `asOf`",
    "   (`YYYY-MM-DD`, the day you fetched the page), and `short` (at most 8 words, the text a",
    "   slide cell shows; name the surface when a product has two), and `chip` (the compact text a",
    "   slide cell shows, in the format below). Factories carry one cell per component; task-queue",
    "   products carry one `queue` cell. Omitted cells have no chip; slides show `–` for them.",
    "2. `chip` format by component:",
    "   - Marks (`plan-hitl`, `plan-persist`, `plan-contents`, `verify-runs-app`, `loop-includes-plan`,",
    "     `design-reads`, `design-reuse`):",
    "     exactly one of `✓` (yes), `✗` (no, only where a cited page states it), `◐` (partly or mixed).",
    "   - Labels, one or two joined by ` + `: `verify-judge` from Check, Model, Agent, Person;",
    "     `verify-keeps-going` from Goal, Hook, Auto-fix, Prompt, Autopilot; `loop-starts-next` from",
    "     Event, Schedule, Finished run, Person; `design-form` from File, Chat; `design-approval`",
    "     from Human, Human approves, Automated; `design-tasks` from Plan steps, Parallel, Tickets, Same session.",
    "   - Names (`plan-name`, `execute-name`, and a task-queue `queue` cell): the product's own term,",
    "     at most 3 words, never a docs page title.",
    "3. `demoable` and `destination` need the same source and date unless they are explicitly",
    "   `unknown` (`kind: \"unknown\"` / `summary: \"unknown\"`).",
    "4. If you cannot find a first-party page that supports a cell, replace it with",
    "   `{ \"omitted\": \"reason\" }`; the reason names the pages checked. Never fill a cell from memory.",
    "5. Run `bun scripts/render-landscape.ts` to regenerate this file, then",
    "   `bun scripts/check-landscape.ts` (also run in CI) to validate.",
    "",
  );
  return out.join("\n");
}

if (import.meta.main) {
  const data = JSON.parse(readFileSync("landscape/matrix.json", "utf8")) as Landscape;
  writeFileSync("landscape/README.md", renderLandscape(data));
  console.log("wrote landscape/README.md");
}
